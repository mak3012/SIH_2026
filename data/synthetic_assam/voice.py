"""Short synthetic "expert voice notes" with offline TTS (espeak-ng) and exact transcripts.

Each note starts by saying it is synthetic (an audible watermark) and the WAV carries a RIFF
LIST/INFO chunk with SYNTHETIC in its comment. The transcript is the exact text spoken, so it
is ground truth for speech-to-text. Without espeak-ng on PATH, notes are skipped with a warning.
"""

import random
import shutil
import struct
import subprocess
import sys
import wave
from pathlib import Path

from synthetic_assam.model import Event, Well

# espeak-ng voice -> accent label. espeak-ng has no Indian English voice; add one (for example
# a licence-checked Piper model) before relying on accent coverage for Indian speakers.
VOICES = [
    ("en-us", "American"),
    ("en-gb-x-rp", "British RP"),
    ("en-gb-scotland", "Scottish"),
    ("en-029", "Caribbean"),
    ("en-gb-x-gbclan", "Lancashire"),
    ("en-gb-x-gbcwmd", "West Midlands"),
]
ROLES = ["drilling supervisor", "mud engineer", "company man", "tool pusher"]
SPOKEN = {"loss": "we had losses", "stuck_pipe": "we got stuck", "kick": "we took a kick"}


def espeak() -> str | None:
    return shutil.which("espeak-ng") or shutil.which("espeak")


def script(well: Well, e: Event) -> str:
    """What the speaker says. Numbers as digits; depths in the well's reporting unit."""
    unit = "feet" if well.depth_unit == "ft" else "metres"
    depth = round(e.md / 0.3048) if well.depth_unit == "ft" else round(e.md)
    parts = [
        "This is a synthetic recording.",
        f"Note on well {well.name.replace('-', ' ')}.",
        f"At about {depth} {unit} in the {e.formation}, {SPOKEN[e.type]}.",
    ]
    if e.loss_bbl is not None:
        parts.append(f"We lost around {e.loss_bbl:g} barrels.")
    if e.pit_gain_bbl is not None:
        parts.append(f"Pit gain was {e.pit_gain_bbl:g} barrels.")
    parts.append(f"Mud weight was {e.mw:.2f}.")
    parts.append(" and ".join(m.lower() for m in e.mitigations).capitalize() + ".")
    if e.root_cause and e.root_cause_status == "recorded":
        parts.append(f"Cause was {e.root_cause.lower()}.")
    parts.append(f"We lost {e.npt_hr:g} hours.")
    return " ".join(parts)


def add_info(path: Path, tags: dict[str, str]) -> float:
    """Rewrite the WAV with correct sizes plus a LIST/INFO chunk. Returns duration in s."""
    with wave.open(str(path), "rb") as r:
        params, frames = r.getparams(), r.readframes(r.getnframes())
    with wave.open(str(path), "wb") as out:
        out.setparams(params)
        out.writeframes(frames)
    body = b"INFO"
    for key, value in tags.items():
        v = value.encode("ascii", "replace") + b"\0"
        body += key.encode("ascii") + struct.pack("<I", len(v)) + v + (b"\0" if len(v) % 2 else b"")
    data = path.read_bytes()
    riff = data[12:] + b"LIST" + struct.pack("<I", len(body)) + body
    path.write_bytes(b"RIFF" + struct.pack("<I", 4 + len(riff)) + b"WAVE" + riff)
    return params.nframes / params.framerate


def voice_notes(
    well: Well, rng: random.Random, out: Path, limit: int = 2
) -> list[dict[str, object]]:
    exe = espeak()
    if exe is None:
        print(f"  warning: espeak-ng not found; no voice notes for {well.name}", file=sys.stderr)
        return []
    items: list[dict[str, object]] = []
    for e in well.events[:limit]:
        voice, accent = rng.choice(VOICES)
        role = rng.choice(ROLES)
        text = script(well, e)
        wav = out / f"{e.id}.wav"
        wav.parent.mkdir(parents=True, exist_ok=True)
        speed, pitch = rng.randint(140, 175), rng.randint(35, 65)
        subprocess.run(
            [exe, "-v", voice, "-s", str(speed), "-p", str(pitch), "-w", str(wav), text],
            check=True,
            capture_output=True,
        )
        speaker = f"{role} ({accent} accent, synthetic voice)"
        duration = add_info(
            wav,
            {
                "INAM": f"{well.name} voice note {e.id} (SYNTHETIC)",
                "ICMT": "SYNTHETIC DATA - generated by synthetic_assam with espeak-ng. Not real.",
                "IART": speaker,
                "ISFT": f"synthetic_assam; espeak-ng voice {voice}",
            },
        )
        wav.with_suffix(".txt").write_text(text + "\n", encoding="utf-8")
        items.append(
            {
                "path": wav,
                "transcript": text,
                "event_id": e.id,
                "voice": voice,
                "accent": accent,
                "speaker": speaker,
                "speed_wpm": speed,
                "pitch": pitch,
                "duration_s": round(duration, 2),
                "lang": "en",
            }
        )
    return items
