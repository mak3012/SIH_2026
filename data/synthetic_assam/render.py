def rotate_bbox(bbox: list[float], angle: float) -> list[float]:
    """Where a normalised bbox ends up after Image.rotate(angle) about the page centre.
    Uses page-relative units scaled by the A4 aspect so the rotation is not skewed."""
    t = math.radians(angle)
    aspect = H / W
    xs, ys = [], []
    for x, y in ((bbox[0], bbox[1]), (bbox[2], bbox[1]), (bbox[0], bbox[3]), (bbox[2], bbox[3])):
        dx, dy = x - 0.5, (y - 0.5) * aspect
        rx, ry = dx * math.cos(t) + dy * math.sin(t), -dx * math.sin(t) + dy * math.cos(t)
        xs.append(0.5 + rx)
        ys.append(0.5 + ry / aspect)
    clamp = [min(1.0, max(0.0, v)) for v in (min(xs), min(ys), max(xs), max(ys))]
    return [round(v, 4) for v in clamp]


def _font(size: int) -> ImageFont.FreeTypeFont | ImageFont.ImageFont:
    return ImageFont.load_default(size=size)


def _watermark(img: Image.Image) -> None:
    layer = Image.new("L", img.size, 0)
    ImageDraw.Draw(layer).text(
        (img.width / 2, img.height / 2),
        WATERMARK,
        fill=255,
        font=_font(int(img.width / 5.5)),
        anchor="mm",
    )
    layer = layer.rotate(40, resample=Image.Resampling.BICUBIC)
    img.paste(222, mask=layer)
    ImageDraw.Draw(img).text(
        (img.width / 2, img.height - 30), FOOTER, fill=70, font=_font(16), anchor="mm"
    )


def _stamp(img: Image.Image, rng: random.Random, text: str) -> None:
    s = Image.new("L", (420, 200), 0)
    d = ImageDraw.Draw(s)
    d.ellipse((6, 6, 414, 194), outline=255, width=7)
    d.text((210, 80), "RECEIVED", fill=255, font=_font(46), anchor="mm")
    d.text((210, 132), text, fill=255, font=_font(34), anchor="mm")
    s = s.rotate(rng.uniform(-25, 25), expand=True, resample=Image.Resampling.BICUBIC)
    x = rng.randint(img.width // 2, img.width - s.width - 20)
    y = rng.randint(int(img.height * 0.05), int(img.height * 0.3))
    img.paste(rng.randint(60, 110), (x, y), mask=s)


def degrade(
    img: Image.Image, rng: random.Random, fax: bool, angle: float, stamp: str | None
) -> Image.Image:
    img = img.convert("L")
    if stamp:
        _stamp(img, rng, stamp)
    img = img.rotate(angle, resample=Image.Resampling.BICUBIC, fillcolor=255)
    img = img.filter(ImageFilter.GaussianBlur(0.7))
    speck = Image.frombytes("L", img.size, rng.randbytes(img.width * img.height))
    img = ImageChops.darker(img, speck.point(lambda v: 90 if v < 2 else 255))
    w, h = img.size
    if fax:
        img = img.resize((w // 2, h // 2), Image.Resampling.BILINEAR).resize(
            (w, h), Image.Resampling.BILINEAR
        )
        img = img.point(lambda v: 0 if v < 165 else 255)
        d = ImageDraw.Draw(img)
        for _ in range(rng.randint(2, 6)):
            y = rng.randrange(h)
            d.line([(0, y), (w, y)], fill=rng.choice([0, 150]), width=rng.randint(1, 2))
        # Binarising erases the grey watermark and small footer: put back ones a fax keeps.
        layer = Image.new("L", img.size, 0)
        ImageDraw.Draw(layer).text(
            (w / 2, h / 2),
            WATERMARK,
            fill=0,
            font=_font(int(w / 5.5)),
            anchor="mm",
            stroke_width=4,
            stroke_fill=255,
        )
        img.paste(0, mask=layer.rotate(40, resample=Image.Resampling.NEAREST))
        d.rectangle((0, h - 48, w, h), fill=255)
        d.text((w / 2, h - 26), FOOTER, fill=0, font=_font(22), anchor="mm")
    else:
        img = img.point(lambda v: int(18 + v * 0.9))  # grey paper, lifted blacks
    return img


def rasterize(doc: TypedDoc, rng: random.Random, fax: bool, stamp: str) -> list[Image.Image]:
    """Print-and-scan a typed document: render, degrade, and move its field bboxes."""
    pdf = pdfium.PdfDocument(doc.pdf())
    pages = []
    for i in range(len(pdf)):
        img = pdf[i].render(scale=DPI / 72).to_pil()
        angle = rng.uniform(-2.0, 2.0)
        pages.append(
            degrade(img, rng, fax, angle, stamp if i == 0 and rng.random() < 0.7 else None)
        )
        for f in doc.fields:
            if f.page == i + 1:
                f.bbox = rotate_bbox(f.bbox, angle)
    pdf.close()
    return pages


def field_note(
    well: Well, e: Event, fmt: Fmt, rng: random.Random, fonts: list[Path]
) -> tuple[list[Image.Image], list[Field]]:
    """A handwritten field note about one event."""
    w, h = int(210 / 25.4 * DPI), int(297 / 25.4 * DPI)
    img = Image.new("L", (w, h), 246)
    _watermark(img)
    d = ImageDraw.Draw(img)
    for y in range(230, h - 120, 78):
        d.line([(60, y), (w - 60, y)], fill=212, width=2)
    size = rng.randint(46, 56)
    font = ImageFont.truetype(str(rng.choice(fonts)), size) if fonts else _font(size - 8)
    assert e.t_start is not None
    depth_p, depth_v = fmt.depth_u(e.md)
    lines: list[tuple[str, str, Any, str | None]] = [
        ("date", fmt.date(e.t_start.date()), e.t_start.date().isoformat(), None),
        ("well_name", f"Well {well.name}", well.name, None),
        (
            "event_type",
            {"loss": "LOSSES", "stuck_pipe": "STUCK PIPE", "kick": "KICK!"}[e.type],
            e.type,
            None,
        ),
        ("depth_md", f"@ {depth_p}", depth_v, well.depth_unit),
        ("formation", f"in {e.formation}", e.formation, None),
    ]
    if e.loss_bbl is not None:
        lines.append(("loss_bbl", f"lost ~{e.loss_bbl:g} bbl", e.loss_bbl, "bbl"))
    if e.pit_gain_bbl is not None:
        lines.append(("pit_gain_bbl", f"pit gain {e.pit_gain_bbl:g} bbl", e.pit_gain_bbl, "bbl"))
    lines += [
        ("mud_weight", f"MW {e.mw:.2f}  ECD {e.ecd:.2f}", e.mw, "sg"),
        ("mitigation", "Action: " + "; ".join(e.mitigations), e.mitigations, None),
        ("npt_hours", f"NPT {e.npt_hr:g} hrs", e.npt_hr, "h"),
    ]
    fields = []
    ink = rng.randint(15, 60)
    for i, (name, text, value, unit) in enumerate(lines):
        x = (w - 520 if name == "date" else 110) + rng.randint(-12, 12)
        y = (130 if name == "date" else 230 + (i - 1) * 78 - size) + rng.randint(-6, 6)
        d.text((x, y), text, fill=ink, font=font)
        x0, y0, x1, y1 = d.textbbox((x, y), text, font=font)
        fields.append(
            Field(
                name,
                value,
                text,
                unit,
                1,
                [round(x0 / w, 4), round(y0 / h, 4), round(x1 / w, 4), round(y1 / h, 4)],
            )
        )
    angle = rng.uniform(-3.0, 3.0)
    fax = well.spud.year < 1995 and rng.random() < 0.5
    img = degrade(img, rng, fax, angle, None)
    for f in fields:
        f.bbox = rotate_bbox(f.bbox, angle)
    return [img], fields


def save_images(images: list[Image.Image], path: Path, title: str, keywords: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    images = [
        im.convert("1") if im.getextrema() == (0, 255) and len(im.getcolors(3) or []) == 2 else im
        for im in images
    ]
    images[0].save(
        path,
        "PDF",
        save_all=True,
        append_images=images[1:],
        resolution=DPI,
        title=title,
        author="synthetic_assam",
        subject="SYNTHETIC DATA - not a real well",
        keywords=keywords,
        creator="synthetic_assam",
        producer="synthetic_assam",
        creationDate=FIXED_DATE,
        modDate=FIXED_DATE,
    )


def fields_json(fields: list[Field]) -> list[dict[str, Any]]:
    return [asdict(f) for f in fields]
