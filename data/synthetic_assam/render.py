FIXED_DATE = time.gmtime(1767225600)  # 2026-01-01, so rebuilt PDFs are byte-identical
WATERMARK = "SYNTHETIC"
FOOTER = "SYNTHETIC DATA - generated by synthetic_assam for software testing. Not a real well."
OPERATOR = "Synthetic Operator Ltd."
PRINTED: Any = object()  # "the value is the printed text" (None means: printed, but no value)
Cell = tuple[str, str | None, Any, str | None]  # printed, field name, value, unit
EVENT_LABEL = {"loss": "Lost circulation", "stuck_pipe": "Stuck pipe", "kick": "Kick"}
