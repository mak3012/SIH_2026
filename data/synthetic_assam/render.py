DATUM_LABEL = {"WGS84": "WGS 84", "Kalianpur1975": "Kalianpur 1975"}


@dataclass
class Field:
    name: str
    value: Any  # canonical value of what is printed (metres, sg, ISO dates, enum names)
    printed: str
    unit: str | None
    page: int
    bbox: list[float]


class Fmt:
    """How one well's paperwork prints numbers, dates and depths."""

    def __init__(self, well: Well, rng: random.Random) -> None:
        self.unit = well.depth_unit
        self.date_fmt = rng.choice(["%d.%m.%Y", "%d-%b-%Y", "%Y-%m-%d", "%d/%m/%Y"])

    def depth(self, m: float) -> tuple[str, float]:
        """Printed number (no unit) and the canonical metres that number stands for."""
        if self.unit == "ft":
            ft = round(m_to_ft(m))
            return f"{ft:,}", round(ft_to_m(ft), 3)
        v = round(m, 1)
        return f"{v:,.1f}", v

    def depth_u(self, m: float) -> tuple[str, float]:
        s, v = self.depth(m)
        return f"{s} {self.unit}", v

    def date(self, d: date) -> str:
        return d.strftime(self.date_fmt)


def describe(a: Activity, well: Well, fmt: Fmt) -> str:
    """Operation text as printed on a DDR."""
    ev = next((e for e in well.events if e.id == a.event_id), None)
    d0, d1 = fmt.depth_u(a.depth_start)[0], fmt.depth_u(a.depth_end)[0]
    if a.kind == "drill":
        return f'Drilled {a.hole_in}" hole from {d0} to {d1}'
    if ev is not None:
        return narrative(ev, fmt, short=True)
    return {
        "rig_up": "Rigging up / pre-spud checks",
        "circulate": "Circulated hole clean",
        "pooh": "POOH to surface",
        "rih": "RIH to shoe",
        "run_casing": f'Ran {a.hole_in}" casing to {d0}',
        "cement": f'Cemented {a.hole_in}" casing',
        "woc": "Waited on cement",
        "bop": "Nippled up and pressure tested BOP",
        "lot": "Drilled out shoe + 3 m new hole; performed LOT",
        "fit": "Drilled out shoe + 3 m new hole; performed FIT",
        "logging": "Wireline logging",
        "rig_down": "Rigging down",
        "released": "Rig released",
        "rig_repair": "Rig repair (top drive)",
    }[a.kind]


def narrative(e: Event, fmt: Fmt, short: bool = False) -> str:
    depth = fmt.depth_u(e.md)[0]
    if e.type == "loss":
        s = f"Lost circulation at {depth} in {e.formation}; {e.loss_bbl:g} bbl lost."
    elif e.type == "kick":
        s = f"Kick at {depth} in {e.formation}; pit gain {e.pit_gain_bbl:g} bbl. Well shut in."
    else:
        s = f"Pipe stuck at {depth} in {e.formation}."
    if short:
        return s
    s += " " + "; ".join(e.mitigations) + ". " + e.outcome + "."
    if e.root_cause:
        s += f" Cause ({e.root_cause_status}): {e.root_cause}."
    return s


class TypedDoc:
    """reportlab canvas that records the bbox of every value it prints."""

    def __init__(self, title: str, keywords: str) -> None:
        self.buf = io.BytesIO()
        self.c = Canvas(self.buf, pagesize=A4, invariant=1)
        self.c.setTitle(title)
        self.c.setAuthor("synthetic_assam")
        self.c.setSubject("SYNTHETIC DATA - not a real well")
        self.c.setKeywords(keywords)
        self.c.setCreator("synthetic_assam")
        self.fields: list[Field] = []
        self.page = 1
        self._decorate()

    def _decorate(self) -> None:
        c = self.c
        c.saveState()
        c.setFillGray(0.86)
        c.setFont("Helvetica-Bold", 96)
        c.translate(W / 2, H / 2)
        c.rotate(40)
        c.drawCentredString(0, -30, WATERMARK)
        c.restoreState()
        c.setFont("Helvetica", 7)
        c.setFillGray(0.3)
        c.drawCentredString(W / 2, 8 * MM, FOOTER)
        c.drawRightString(W - 15 * MM, 8 * MM, f"Page {self.page}")

    def text(
        self,
        x: float,
        y: float,
        s: str,
        *,
        size: float = 9,
        bold: bool = False,
        name: str | None = None,
        value: Any = PRINTED,
        unit: str | None = None,
    ) -> None:
        """Draw `s` with its baseline at (x, y) mm from the top-left corner."""
        font = "Helvetica-Bold" if bold else "Helvetica"
        self.c.setFont(font, size)
        self.c.setFillGray(0)
        self.c.drawString(x * MM, H - y * MM, s)
        if name:
            asc, desc = getAscentDescent(font, size)
            x0, top, bot = x * MM, y * MM - asc, y * MM - desc
            bbox = [x0 / W, top / H, (x0 + stringWidth(s, font, size)) / W, bot / H]
            self.fields.append(
                Field(
                    name,
                    s if value is PRINTED else value,
                    s,
                    unit,
                    self.page,
                    [round(v, 4) for v in bbox],
                )
            )

    def rule(self, y: float, x0: float = 15, x1: float = 195) -> None:
        self.c.setLineWidth(0.5)
        self.c.line(x0 * MM, H - y * MM, x1 * MM, H - y * MM)

    def new_page(self) -> None:
        self.c.showPage()
        self.page += 1
        self._decorate()

    def table(
        self,
        y: float,
        cols: list[tuple[str, float]],
        rows: list[list[Cell]],
        *,
        size: float = 8.5,
        row_h: float = 5.2,
        y_max: float = 272,
    ) -> float:
        """cols: (header, width mm). Cell: (printed, field name, canonical value, unit)."""

        def header(y: float) -> float:
            x = 15.0
            for title, width in cols:
                self.text(x, y, title, size=size, bold=True)
                x += width
            self.rule(y + 1.5)
            return y + row_h + 0.5

        y = header(y)
        for row in rows:
            if y > y_max:
                self.new_page()
                y = header(25)
            x = 15.0
            for (printed, name, value, unit), (_, width) in zip(row, cols, strict=True):
                self.text(x, y, printed, size=size, name=name, value=value, unit=unit)
                x += width
            y += row_h
        return y

    def pdf(self) -> bytes:
        self.c.showPage()
        self.c.save()
        return self.buf.getvalue()


def _kv(
    doc: TypedDoc,
    y: float,
    label: str,
    printed: str,
    name: str,
    value: Any,
    unit: str | None = None,
) -> float:
    doc.text(20, y, label, size=10)
    doc.text(75, y, printed, size=10, name=name, value=value, unit=unit)
    return y + 7


def _coords(well: Well) -> tuple[str, str]:
    if well.coord_datum == "WGS84" and well.spud.year >= 2005:
        return f"{abs(well.lat_printed_datum):.5f}° N", f"{abs(well.lon_printed_datum):.5f}° E"
    return to_dms(well.lat_printed_datum, "N", "S"), to_dms(well.lon_printed_datum, "E", "W")


def wcr(well: Well, fmt: Fmt, keywords: str) -> TypedDoc:
    u = well.depth_unit
    doc = TypedDoc(f"{well.name} Well Completion Report (SYNTHETIC)", keywords)
    doc.text(20, 25, "WELL COMPLETION REPORT", size=16, bold=True)
    doc.text(20, 33, OPERATOR, size=10)
    doc.rule(37)
    lat, lon = _coords(well)
    datum_elev = fmt.depth_u(well.datum_elev)
    ground = fmt.depth_u(well.ground_elev)
    y = 47.0
    for label, printed, name, value, unit in [
        ("Well name", well.name, "well_name", well.name, None),
        ("Block", well.block, "block", well.block, None),
        ("Field", well.field, "field", well.field, None),
        ("Latitude", lat, "latitude", round(well.lat_printed_datum, 6), "deg"),
        ("Longitude", lon, "longitude", round(well.lon_printed_datum, 6), "deg"),
        (
            "Coordinate datum",
            DATUM_LABEL[well.coord_datum],
            "coordinate_datum",
            well.coord_datum,
            None,
        ),
        ("Depth reference", well.datum, "depth_reference", well.datum, None),
        (f"{well.datum} elevation", f"{datum_elev[0]} AMSL", "datum_elevation", datum_elev[1], u),
        ("Ground level", f"{ground[0]} AMSL", "ground_elevation", ground[1], u),
        ("Spud date", fmt.date(well.spud.date()), "spud_date", well.spud.date().isoformat(), None),
        (
            "Rig release",
            fmt.date(well.completed.date()),
            "completion_date",
            well.completed.date().isoformat(),
            None,
        ),
        ("Total depth (MD)", fmt.depth_u(well.td_md)[0], "td_md", fmt.depth(well.td_md)[1], u),
        ("Total depth (TVD)", fmt.depth_u(well.td_tvd)[0], "td_tvd", fmt.depth(well.td_tvd)[1], u),
        ("Well profile", PROFILE[well.trajectory], "trajectory_type", well.trajectory, None),
    ]:
        y = _kv(doc, y, label, printed, name, value, unit)
    doc.text(20, y + 6, f"All depths in {u} below {well.datum} unless stated.", size=9)

    doc.new_page()
    doc.text(20, 25, "FORMATION TOPS", size=13, bold=True)
    rows: list[list[Cell]] = []
    for i, top in enumerate(well.tops):
        cells: list[Cell] = [(top.formation, f"tops[{i}].formation", top.formation, None)]
        for key, v in (("md", top.md), ("tvd", top.tvd), ("tvdss", top.tvdss)):
            printed, canon = fmt.depth(v)
            cells.append((printed, f"tops[{i}].{key}", canon, u))
        rows.append(cells)
    doc.table(
        35, [("Formation", 50), (f"MD ({u})", 35), (f"TVD ({u})", 35), (f"TVDSS ({u})", 35)], rows
    )

    doc.new_page()
    doc.text(20, 25, "CASING AND CEMENTING", size=13, bold=True)
    rows = []
    for i, c in enumerate(well.casing):
        md_p, md_v = fmt.depth(c.shoe_md)
        tvd_p, tvd_v = fmt.depth(c.shoe_tvd)
        rows.append(
            [
                (f'{c.od_in}"', f"casing[{i}].od_in", c.od_in, "in"),
                (f'{c.hole_in}"', f"casing[{i}].hole_in", c.hole_in, "in"),
                (md_p, f"casing[{i}].shoe_md", md_v, u),
                (tvd_p, f"casing[{i}].shoe_tvd", tvd_v, u),
                (f"{c.weight_ppf:g}", f"casing[{i}].weight_ppf", c.weight_ppf, "lb/ft"),
                (c.grade, f"casing[{i}].grade", c.grade, None),
            ]
        )
    y = doc.table(
        35,
        [
            ("Casing", 25),
            ("Hole", 25),
            (f"Shoe MD ({u})", 32),
            (f"Shoe TVD ({u})", 32),
            ("Wt (lb/ft)", 25),
            ("Grade", 25),
        ],
        rows,
    )
    doc.text(20, y + 10, "LEAK-OFF / FORMATION INTEGRITY TESTS", size=13, bold=True)
    rows = []
    for i, lf in enumerate(well.lot_fit):
        md_p, md_v = fmt.depth(lf.md)
        rows.append(
            [
                (lf.test_type.upper(), f"lot_fit[{i}].test_type", lf.test_type, None),
                (f'{lf.casing}"', f"lot_fit[{i}].casing", lf.casing, "in"),
                (md_p, f"lot_fit[{i}].md", md_v, u),
                (f"{lf.emw:.2f}", f"lot_fit[{i}].emw", lf.emw, "sg"),
            ]
        )
    doc.table(
        y + 20, [("Test", 25), ("Below shoe", 30), (f"Depth MD ({u})", 35), ("EMW (sg)", 30)], rows
    )

    doc.new_page()
    doc.text(20, 25, "DRILLING PROBLEMS", size=13, bold=True)
    if not well.events:
        doc.text(20, 37, "No significant drilling problems recorded.", size=10)
    rows = []
    for i, e in enumerate(well.events):
        md_p, md_v = fmt.depth(e.md)
        vol = e.loss_bbl if e.type == "loss" else e.pit_gain_bbl
        assert e.t_start is not None
        rows.append(
            [
                (
                    fmt.date(e.t_start.date()),
                    f"events[{i}].date",
                    e.t_start.date().isoformat(),
                    None,
                ),
                (EVENT_LABEL[e.type], f"events[{i}].type", e.type, None),
                (md_p, f"events[{i}].md", md_v, u),
                (e.formation, f"events[{i}].formation", e.formation, None),
                (f"{e.npt_hr:g}", f"events[{i}].npt_hr", e.npt_hr, "h"),
                ("-" if vol is None else f"{vol:g}", f"events[{i}].volume_bbl", vol, "bbl"),
                (f"{e.mw:.2f}", f"events[{i}].mw", e.mw, "sg"),
            ]
        )
    if rows:
        doc.table(
            35,
            [
                ("Date", 26),
                ("Problem", 30),
                (f"MD ({u})", 24),
                ("Formation", 28),
                ("NPT (h)", 20),
                ("Vol (bbl)", 22),
                ("MW (sg)", 20),
            ],
            rows,
        )
    return doc


def ddr(well: Well, day: Day, fmt: Fmt, keywords: str) -> TypedDoc:
    u = well.depth_unit
    doc = TypedDoc(f"{well.name} Daily Drilling Report {day.no} (SYNTHETIC)", keywords)
    doc.text(15, 22, "DAILY DRILLING REPORT", size=15, bold=True)
    doc.text(15, 29, OPERATOR, size=9)
    doc.rule(32)
    depth_p, depth_v = fmt.depth_u(day.depth_end)
    prog_p, prog_v = fmt.depth_u(day.depth_end - day.depth_start)
    hole = next((a.hole_in for a in reversed(day.activities) if a.kind == "drill"), "")
    head = [
        (15, 40, "Well:", well.name, "well_name", well.name, None),
        (80, 40, "Report no:", str(day.no), "report_no", day.no, None),
        (140, 40, "Date:", fmt.date(day.date), "report_date", day.date.isoformat(), None),
        (15, 47, "Depth @ 24:00:", depth_p, "depth_md", depth_v, u),
        (80, 47, "Progress:", prog_p, "progress", prog_v, u),
        (140, 47, "MW:", f"{day.mw:.2f} sg", "mud_weight", day.mw, "sg"),
    ]
    for hx, hy, label, printed, name, value, unit in head:
        doc.text(hx, hy, label, size=9, bold=True)
        doc.text(
            hx + (27 if label.startswith("Depth") else 19),
            hy,
            printed,
            size=9,
            name=name,
            value=value,
            unit=unit,
        )
    if hole:
        doc.text(15, 54, "Hole size:", size=9, bold=True)
        doc.text(34, 54, f'{hole}"', size=9, name="hole_size", value=hole, unit="in")

    doc.text(15, 64, "TIME BREAKDOWN", size=11, bold=True)
    rows: list[list[Cell]] = []
    for i, a in enumerate(day.activities):
        to = "24:00" if a.end.time() == datetime.min.time() else a.end.strftime("%H:%M")
        rows.append(
            [
                (
                    a.start.strftime("%H:%M"),
                    f"time_breakdown[{i}].from",
                    a.start.strftime("%H:%M"),
                    None,
                ),
                (to, f"time_breakdown[{i}].to", to, None),
                (f"{a.hours:.2f}", f"time_breakdown[{i}].hours", round(a.hours, 2), "h"),
                (a.code, f"time_breakdown[{i}].code", a.code, None),
                (describe(a, well, fmt), f"time_breakdown[{i}].description", PRINTED, None),
            ]
        )
    y = doc.table(
        72, [("From", 15), ("To", 15), ("Hrs", 15), ("Code", 22), ("Operation", 115)], rows, size=8
    )
    npt = sum(a.hours for a in day.activities if a.npt)
    doc.text(15, y + 4, "Total hours:", size=9, bold=True)
    doc.text(
        38,
        y + 4,
        f"{sum(a.hours for a in day.activities):.2f}",
        size=9,
        name="total_hours",
        value=24.0,
        unit="h",
    )
    doc.text(80, y + 4, "NPT today:", size=9, bold=True)
    doc.text(100, y + 4, f"{npt:.2f} hrs", size=9, name="npt_hours", value=round(npt, 2), unit="h")
    y += 14
    doc.text(15, y, "REMARKS", size=11, bold=True)
    for k, eid in enumerate(day.event_ids):
        e = next(x for x in well.events if x.id == eid)
        y += 6
        doc.text(15, y, narrative(e, fmt, short=True), size=8.5, name=f"remarks[{k}]", value=e.type)
    if not day.event_ids:
        doc.text(15, y + 6, "Operations normal.", size=8.5)
    return doc


def survey_report(well: Well, fmt: Fmt, keywords: str) -> TypedDoc:
    u = well.depth_unit
    doc = TypedDoc(f"{well.name} Directional Survey Report (SYNTHETIC)", keywords)
    doc.text(15, 22, "DIRECTIONAL SURVEY REPORT", size=15, bold=True)
    doc.text(
        15,
        29,
        f"Well {well.name}   Depth reference {well.datum}   Units {u}, degrees",
        size=9,
        name="well_name",
        value=well.name,
    )
    rows: list[list[Cell]] = []
    for i, s in enumerate(well.survey):
        cells: list[Cell] = []
        for key, v in (("md", s.md), ("tvd", s.tvd), ("north", s.north), ("east", s.east)):
            p, c = fmt.depth(v)
            cells.append((p, f"survey[{i}].{key}", c, u))
        cells.insert(1, (f"{s.inc:.2f}", f"survey[{i}].inc", s.inc, "deg"))
        cells.insert(2, (f"{s.azi:.2f}", f"survey[{i}].azi", s.azi, "deg"))
        rows.append(cells)
    doc.table(
        38,
        [
            (f"MD ({u})", 28),
            ("Inc", 22),
            ("Azi", 22),
            (f"TVD ({u})", 28),
            (f"N/S ({u})", 28),
            (f"E/W ({u})", 28),
        ],
        rows,
        size=8,
        row_h=4.6,
    )
    return doc


