def run(sql: str) -> None:
    # Raw driver call: multi-statement SQL, no bind-parameter parsing of ':' or '%'.
    op.get_bind().connection.driver_connection.execute(sql)


def upgrade() -> None:
    run("""
    CREATE EXTENSION IF NOT EXISTS timescaledb;
    CREATE EXTENSION IF NOT EXISTS postgis;
    CREATE EXTENSION IF NOT EXISTS vector;

    -- Access scopes. Every protected row resolves to one block and optionally one JV.
    CREATE TABLE block (
        id    text PRIMARY KEY,
        name  text NOT NULL,
        basin text
    );
    COMMENT ON TABLE block IS 'Licence block. Primary ABAC attribute.';

    CREATE TABLE jv (
        id       text PRIMARY KEY,
        name     text NOT NULL,
        operator text
    );
    COMMENT ON TABLE jv IS 'Joint venture. Secondary ABAC attribute: JV partners see JV rows.';

    -- ABAC predicate. Session attributes are set per request (see api.db.scoped):
    --   app.blocks = 'B1,B2'   app.jvs = 'JV1'
    -- Unset attributes mean no access (deny by default).
    CREATE FUNCTION app_visible(p_block text, p_jv text) RETURNS boolean
    LANGUAGE sql STABLE AS $$
        SELECT coalesce(
            p_block = ANY (string_to_array(nullif(current_setting('app.blocks', true), ''), ','))
            OR p_jv = ANY (string_to_array(nullif(current_setting('app.jvs', true), ''), ',')),
            false)
    $$;

    CREATE TYPE doc_type AS ENUM (
        'wcr', 'ddr', 'mud_log', 'survey_report', 'geology_report', 'test_report', 'other');
    CREATE TYPE classification AS ENUM ('public', 'internal', 'restricted', 'confidential');
    CREATE TYPE review_status AS ENUM ('pending', 'accepted', 'corrected', 'rejected');

    CREATE TABLE document (
        id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        sha256         bytea NOT NULL UNIQUE CHECK (octet_length(sha256) = 32),
        type           doc_type NOT NULL,
        title          text NOT NULL,
        vintage        date,
        classification classification NOT NULL DEFAULT 'internal',
        uri            text NOT NULL,
        page_count     int CHECK (page_count > 0),
        block_id       text NOT NULL REFERENCES block,
        jv_id          text REFERENCES jv,
        ingested_at    timestamptz NOT NULL DEFAULT now()
    );
    COMMENT ON TABLE document IS
        'Source file (scan, PDF, report). Bytes live in object storage at uri; sha256 dedupes.';

    CREATE TABLE audio_note (
        id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        sha256      bytea NOT NULL UNIQUE CHECK (octet_length(sha256) = 32),
        uri         text NOT NULL,
        duration_s  real NOT NULL CHECK (duration_s > 0),
        speaker     text,
        lang        text NOT NULL DEFAULT 'en',
        recorded_at timestamptz,
        block_id    text NOT NULL REFERENCES block,
        jv_id       text REFERENCES jv,
        ingested_at timestamptz NOT NULL DEFAULT now()
    );
    COMMENT ON TABLE audio_note IS 'Voice note from site or review. lang is BCP-47.';

    -- One row per extracted value's origin. Every fact row points at exactly one source_ref.
    CREATE TABLE source_ref (
        id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        document_id       bigint REFERENCES document ON DELETE RESTRICT,
        audio_note_id     bigint REFERENCES audio_note ON DELETE RESTRICT,
        page              int CHECK (page > 0),
        bbox              real[] CHECK (bbox IS NULL OR (cardinality(bbox) = 4
                              AND bbox[1] < bbox[3] AND bbox[2] < bbox[4])),
        t_start           real CHECK (t_start >= 0),
        t_end             real,
        extractor_version text NOT NULL,
        confidence        real CHECK (confidence BETWEEN 0 AND 1),
        review_status     review_status NOT NULL DEFAULT 'pending',
        reviewer          text,
        reviewed_at       timestamptz,
        created_at        timestamptz NOT NULL DEFAULT now(),
        CHECK (num_nonnulls(document_id, audio_note_id) = 1),
        CHECK (audio_note_id IS NULL OR (page IS NULL AND bbox IS NULL)),
        CHECK (document_id IS NULL OR (t_start IS NULL AND t_end IS NULL)),
        CHECK (t_end IS NULL OR t_end >= t_start),
        CHECK ((review_status = 'pending') = (reviewer IS NULL AND reviewed_at IS NULL))
    );
    COMMENT ON TABLE source_ref IS
        'Provenance: where a value came from (document page + bbox, or audio time span), '
        'which extractor produced it, and its human review state.';
    CREATE INDEX ON source_ref (document_id);
    CREATE INDEX ON source_ref (audio_note_id);

    -- Retrieval passages. Citation resolves through source_ref (document/page/bbox or audio span).
    CREATE TABLE chunk (
        id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        source_ref_id bigint NOT NULL REFERENCES source_ref ON DELETE CASCADE,
        text          text NOT NULL,
        tsv           tsvector GENERATED ALWAYS AS (to_tsvector('english', text)) STORED,
        embedding     vector(1024),
        created_at    timestamptz NOT NULL DEFAULT now()
    );
    COMMENT ON TABLE chunk IS
        'Passage for hybrid retrieval: full-text (tsv) + semantic (embedding, 1024-d, cosine).';
    CREATE INDEX ON chunk (source_ref_id);
    CREATE INDEX ON chunk USING gin (tsv);
    CREATE INDEX ON chunk USING hnsw (embedding vector_cosine_ops);

    -- Shared stratigraphic reference data (not access-controlled).
    CREATE TABLE formation (
        id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        basin         text NOT NULL,
        name          text NOT NULL,
        parent_id     bigint REFERENCES formation,
        synonyms      text[] NOT NULL DEFAULT '{}',
        source_ref_id bigint REFERENCES source_ref,
        UNIQUE (basin, name)
    );
    COMMENT ON TABLE formation IS
        'Stratigraphic unit per basin. parent_id builds group > formation > member. '
        'synonyms holds alternative spellings/names seen in reports.';
    CREATE INDEX ON formation USING gin (synonyms);
    """)


