def run(sql: str) -> None:
    # Raw driver call: multi-statement SQL, no bind-parameter parsing of ':' or '%'.
    op.get_bind().connection.driver_connection.execute(sql)


def upgrade() -> None:
    run("""
    CREATE TABLE rt_feed (
        id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        wellbore_id    bigint NOT NULL REFERENCES wellbore ON DELETE CASCADE,
        connector      text NOT NULL CHECK (connector IN (
                           'witsml', 'etp', 'wits0', 'opcua', 'sql', 'simulator')),
        config         jsonb NOT NULL DEFAULT '{}',
        state          text NOT NULL DEFAULT 'disconnected'
                           CHECK (state IN ('live', 'stale', 'disconnected', 'stopped')),
        last_sample_ts timestamptz,
        last_rx_at     timestamptz,
        updated_at     timestamptz NOT NULL DEFAULT now(),
        UNIQUE (wellbore_id, connector)
    );
    COMMENT ON TABLE rt_feed IS
        'One real-time connector per wellbore. state: live (data arriving), stale (no new data '
        'for stale_after_s although the connector runs), disconnected (connector failing), '
        'stopped. last_sample_ts is data time, last_rx_at wall-clock receive time. config '
        'never holds secrets.';

    CREATE TABLE rt_gap (
        id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        wellbore_id bigint NOT NULL REFERENCES wellbore ON DELETE CASCADE,
        feed_id     bigint REFERENCES rt_feed ON DELETE SET NULL,
        kind        text NOT NULL CHECK (kind IN ('stale', 'data_gap')),
        gap_start   timestamptz NOT NULL,
        gap_end     timestamptz,
        CHECK (gap_end IS NULL OR gap_end >= gap_start)
    );
    COMMENT ON TABLE rt_gap IS
        'stale: wall-clock period without new data (detectors paused); data_gap: a jump in '
        'sample time larger than the feed interval allows (windows across it are discarded).';
    CREATE INDEX ON rt_gap (wellbore_id, gap_start DESC);

    CREATE TABLE alert_shelf (
        id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        wellbore_id  bigint NOT NULL REFERENCES wellbore ON DELETE CASCADE,
        hazard       event_type NOT NULL,
        reason       text NOT NULL CHECK (length(trim(reason)) >= 5),
        shelved_by   text NOT NULL,
        shelved_at   timestamptz NOT NULL DEFAULT now(),
        expires_at   timestamptz NOT NULL,
        unshelved_by text,
        unshelved_at timestamptz,
        -- ISA-18.2: shelving is temporary, explained and attributed. At most one shift.
        CHECK (expires_at > shelved_at AND expires_at <= shelved_at + interval '12 hours'),
        CHECK ((unshelved_by IS NULL) = (unshelved_at IS NULL))
    );
    COMMENT ON TABLE alert_shelf IS
        'Shelved hazard on a wellbore: advisory and warning alerts are recorded but not '
        'delivered until expires_at or unshelving. Critical alerts are never shelved.';
    CREATE INDEX ON alert_shelf (wellbore_id, expires_at);

    ALTER TABLE alert
        ADD COLUMN formation          text,
        ADD COLUMN rig_state          rig_state,
        ADD COLUMN last_seen_at       timestamptz,
        ADD COLUMN cleared_at         timestamptz,
        ADD COLUMN peak_posterior     real,
        ADD COLUMN updates            integer NOT NULL DEFAULT 0,
        ADD COLUMN suppressed         text CHECK (suppressed IN ('shelved', 'budget')),
        ADD COLUMN shelf_id           bigint REFERENCES alert_shelf,
        ADD COLUMN detector_version   text,
        ADD COLUMN calibrated         boolean,
        ADD COLUMN explanation_status text NOT NULL DEFAULT 'none' CHECK (explanation_status IN (
                                          'none', 'pending', 'done', 'failed', 'timeout',
                                          'disabled')),
        ADD COLUMN explanation_error  text,
        ADD COLUMN llm_citations      jsonb,
        ADD CHECK (suppressed <> 'shelved' OR shelf_id IS NOT NULL),
        ADD CHECK (suppressed IS NULL OR tier < 3);
    COMMENT ON COLUMN alert.raised_at IS 'Data time of the sample that raised the alert.';
    COMMENT ON COLUMN alert.suppressed IS
        'Recorded but not delivered: shelved (alert_shelf) or over the per-shift advisory budget.';
    COMMENT ON COLUMN alert.explanation_status IS
        'LLM explainer state. The alert exists and is delivered before the explainer runs; '
        'failed / timeout leave the alert unchanged.';

    ALTER TABLE llm_call ADD COLUMN alert_id bigint REFERENCES alert ON DELETE SET NULL;
    """)
